create table if not exists public.backoffice_leads (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'manual',
  source_event_id text,
  lead_status text not null default 'new' check (lead_status in ('new','contacted','qualified','nurture','closed','archived')),
  processing_status text not null default 'pending' check (processing_status in ('pending','processing','ready','review','error')),
  full_name text not null default '',
  email text,
  phone text,
  submitted_address text,
  submitted_address_json jsonb not null default '{}'::jsonb,
  standardized_address text,
  standardized_address_json jsonb not null default '{}'::jsonb,
  address_status text not null default 'pending' check (address_status in ('pending','verified','corrected','review','error','skipped')),
  tenure text,
  household_income text,
  program text,
  intent_score smallint check (intent_score is null or intent_score between 0 and 100),
  intent_label text,
  estimated_benefit numeric(12,2) check (estimated_benefit is null or estimated_benefit >= 0),
  tags text[] not null default '{}'::text[],
  identity_score numeric(5,2) check (identity_score is null or identity_score between 0 and 100),
  identity_status text not null default 'pending' check (identity_status in ('pending','matched','partial','review','no_match','error','skipped')),
  enrichment_provider text,
  enrichment_data jsonb not null default '{}'::jsonb,
  crm_provider text not null default 'boldtrail',
  crm_status text not null default 'pending' check (crm_status in ('pending','queued','synced','review','error','skipped')),
  crm_contact_id text,
  crm_synced_at timestamptz,
  crm_error text,
  consent_data jsonb not null default '{}'::jsonb,
  raw_payload jsonb not null default '{}'::jsonb,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists backoffice_leads_source_event_uidx
  on public.backoffice_leads (source, source_event_id)
  where source_event_id is not null;
create index if not exists backoffice_leads_created_idx on public.backoffice_leads (created_at desc);
create index if not exists backoffice_leads_processing_idx on public.backoffice_leads (processing_status, created_at desc);
create index if not exists backoffice_leads_crm_idx on public.backoffice_leads (crm_status, created_at desc);
create index if not exists backoffice_leads_email_idx on public.backoffice_leads (lower(email)) where email is not null;
create index if not exists backoffice_leads_phone_idx on public.backoffice_leads (phone) where phone is not null;

create table if not exists public.backoffice_lead_events (
  id bigint generated by default as identity primary key,
  lead_id uuid not null references public.backoffice_leads(id) on delete cascade,
  event_type text not null,
  status text,
  provider text,
  details jsonb not null default '{}'::jsonb,
  actor_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists backoffice_lead_events_lead_idx on public.backoffice_lead_events (lead_id, created_at desc);

create or replace function public.touch_backoffice_lead_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_backoffice_leads_updated_at on public.backoffice_leads;
create trigger trg_backoffice_leads_updated_at
before update on public.backoffice_leads
for each row execute function public.touch_backoffice_lead_updated_at();

