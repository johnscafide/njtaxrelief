// Builds the Watchdog glossary index page and its sitemap from
// property/data/glossary.json (the single source of truth).
//
//   node scripts/build-glossary.mjs           write the files
//   node scripts/build-glossary.mjs --check   fail if either file is stale
//
// Outputs: property/glossary/index.html (served at /glossary) and
// sitemap-glossary.xml. Term pages are rendered on request by api/glossary.js.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DATA = path.join(ROOT, 'property', 'data', 'glossary.json');
const INDEX = path.join(ROOT, 'property', 'glossary', 'index.html');
const SITEMAP = path.join(ROOT, 'sitemap-glossary.xml');
const ORIGIN = 'https://www.watchdogindex.com';

const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const json = (o) => JSON.stringify(o).replace(/</g, '\\u003c');

const doc = JSON.parse(readFileSync(DATA, 'utf8'));
const categories = doc.categories;
const terms = doc.terms.slice().sort((a, b) => a.term.localeCompare(b.term, 'en', { sensitivity: 'base' }));
const searchText = (t) => [t.term, t.slug.replace(/-/g, ' '), ...(t.aliases || []), t.definition].join(' ').toLowerCase();

const sections = categories.map((c) => {
  const list = terms.filter((t) => t.category === c.id);
  const cards = list.map((t) => `<a class="gl-term" href="/glossary/${t.slug}" data-search="${esc(searchText(t))}"><strong>${esc(t.term)}</strong><span>${esc(t.definition)}</span></a>`).join('\n      ');
  return `  <section class="gl-section" id="${c.id}" aria-labelledby="${c.id}-title">
    <h2 id="${c.id}-title">${esc(c.label)}</h2>
    <p>${esc(c.blurb)}</p>
    <div class="gl-grid">
      ${cards}
    </div>
  </section>`;
});
const jump = categories.map((c) => `<li><a href="#${c.id}">${esc(c.label)} <span>${terms.filter((t) => t.category === c.id).length}</span></a></li>`).join('');

const schema = {
  '@context': 'https://schema.org',
  '@type': 'DefinedTermSet',
  '@id': `${ORIGIN}/glossary`,
  name: 'Watchdog New Jersey property glossary',
  url: `${ORIGIN}/glossary`,
  description: 'Plain-English definitions for New Jersey property tax, relief program, home buying, mortgage and renting terms, each tied to an official New Jersey source.',
  hasDefinedTerm: terms.map((t) => ({ '@type': 'DefinedTerm', name: t.term, url: `${ORIGIN}/glossary/${t.slug}` }))
};

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="index,follow">
<title>New Jersey Property Glossary: Taxes, Relief, Buying and Renting | Watchdog</title>
<meta name="description" content="Plain-English definitions for ${terms.length} New Jersey property terms: tax bills, assessments, appeals, ANCHOR and Senior Freeze, buying, mortgages and renting. Each one cites an official source.">
<link rel="canonical" href="${ORIGIN}/glossary">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Playfair+Display:wght@600&family=Plus+Jakarta+Sans:wght@500;700;800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/property/css/watchdog-games.css?v=20261001c">
<link rel="stylesheet" href="/property/css/watchdog-glossary.css?v=20261001a">
<script type="application/ld+json">${json(schema)}</script>
</head>
<body class="wg">
<!-- Generated by scripts/build-glossary.mjs from property/data/glossary.json. Edit the data, then rebuild. -->
<a class="wg-skip" href="#wg-main">Skip to the glossary</a>
<header class="wg-bar"><div class="wg-bar-in">
  <a class="wg-brand" href="/">Watchdog</a>
  <nav class="wg-nav" aria-label="Learn"><a href="/games">Games</a><a href="/glossary" aria-current="page">Glossary</a><a href="/">Look up a home</a></nav>
</div></header>

<main class="wg-main" id="wg-main">
  <h1>New Jersey property glossary</h1>
  <p class="wg-lede">Plain-English definitions for the words on your tax bill, your relief application, your closing papers and your lease. Every term links to the official New Jersey source it comes from.</p>
  <div class="gl-search">
    <label for="gl-q">Search the glossary</label>
    <input id="gl-q" type="search" placeholder="Try ANCHOR or escrow" autocomplete="off">
    <p class="gl-count" id="gl-count" aria-live="polite">${terms.length} terms</p>
  </div>
  <ul class="gl-jump" aria-label="Topics">${jump}</ul>
${sections.join('\n')}
  <p class="gl-empty" id="gl-empty" hidden>No terms match that. Try a shorter word, or <a href="/contact">tell us what's missing</a>.</p>
  <section class="wg-card">
    <h2>Test yourself</h2>
    <p>Watchdog Games are quick daily puzzles built from the same public records these terms describe.</p>
    <a class="wg-btn wg-btn-quiet" href="/games">Play today's games</a>
  </section>
</main>

<footer class="wg-foot"><div class="wg-foot-in"><span>Watchdog glossary</span><a href="/games">Games</a><a href="/privacy">Privacy</a><a href="/terms">Terms</a></div></footer>
<script src="/property/js/glossary-search.js?v=20261001a"></script>
</body>
</html>
`;

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${ORIGIN}/glossary</loc><lastmod>${doc.generated_at}</lastmod></url>
${terms.map((t) => `  <url><loc>${ORIGIN}/glossary/${t.slug}</loc><lastmod>${t.updated || doc.generated_at}</lastmod></url>`).join('\n')}
</urlset>
`;

const outputs = [[INDEX, html], [SITEMAP, sitemap]];
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, body]) => { try { return readFileSync(file, 'utf8') !== body; } catch (_) { return true; } });
  stale.forEach(([file]) => console.error('stale: ' + path.relative(ROOT, file)));
  if (stale.length) { console.error('Run: node scripts/build-glossary.mjs'); process.exit(1); }
  console.log(`Glossary page and sitemap are current (${terms.length} terms).`);
} else {
  outputs.forEach(([file, body]) => writeFileSync(file, body));
  console.log(`Wrote the glossary page and sitemap for ${terms.length} terms in ${categories.length} topics.`);
}
