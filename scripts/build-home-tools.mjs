// Builds property/js/dashboard/home/home-tools.js: every dashboard tool module
// that Property Home's analysis sections call, as one classic script.
//
// Property Home is a single bundle (property/js/home.js) that deliberately does
// not dynamically import modules, but its sections still call the tool
// functions (toolSeniorBenefits, townIntelligenceCard, ...). This file supplies
// them. Each module keeps its own scope, exactly as it had as an ES module;
// modules already publish what they share on window.
//
//   node scripts/build-home-tools.mjs           write the file
//   node scripts/build-home-tools.mjs --check   fail if the file is stale
import fs from 'node:fs';

const OUT = 'property/js/dashboard/home/home-tools.js';
const TOOLS = 'property/js/dashboard/tools/';
const src = fs.readFileSync('property/js/dashboard/home/index.js', 'utf8');

function objectLiteral(name) {
  const m = src.match(new RegExp('var ' + name + ' = \\{([\\s\\S]*?)\\n  \\};'));
  if (!m) throw new Error('Could not find ' + name + ' in property/js/dashboard/home/index.js');
  return Function('return {' + m[1] + '}')();
}

const deps = objectLiteral('homeModuleDependencies');
const sections = objectLiteral('HOME_SECTION_MODULES');
const order = [];
function add(name) {
  (deps[name] || []).forEach(add);
  if (!order.includes(name)) order.push(name);
}
Object.values(sections).flat().forEach(add);
add('watchdog-score');

function strip(code, file) {
  const lines = code.split('\n').filter(line => {
    if (/^\s*import\s+['"]\.\.\/\.\.\/watchdog-score-core\.js['"];?\s*$/.test(line)) return false;
    if (/^\s*import\s/.test(line)) throw new Error(file + ': unsupported import: ' + line.trim());
    if (/^export\s*\{[^}]*\};?\s*$/.test(line)) return false;
    if (/^\s*export\s/.test(line)) throw new Error(file + ': unsupported export: ' + line.trim());
    return true;
  }).map(line => line.replace(/;\s*export\s*\{\s*\};?\s*$/, ';')).map(line => {
    if (/(^|[;})\s])export\s*\{/.test(line)) throw new Error(file + ': unsupported inline export');
    return line;
  });
  return lines.join('\n');
}

let out = '/* Generated by scripts/build-home-tools.mjs. Do not edit by hand.\n' +
  '   Property Home analysis tools as one classic script, loaded before property/js/home.js. */\n';
out += 'window.__wdHomeToolLoads = window.__wdHomeToolLoads || [];\n';
out += '\n/* ===== property/js/watchdog-score-core.js ===== */\n' + fs.readFileSync('property/js/watchdog-score-core.js', 'utf8').trim() + '\n';
for (const name of order) {
  const file = TOOLS + name + '.js';
  const body = strip(fs.readFileSync(file, 'utf8'), file).trim();
  // A module with top-level await becomes an async function; its completion
  // joins NJPropertyToolsReady, which sections wait on before they build.
  const topLevelAwait = body.split('\n').some(line => /^[A-Za-z_$]/.test(line) && line.includes('await '));
  out += '\n/* ===== ' + file + ' ===== */\n' +
    (topLevelAwait
      ? 'window.__wdHomeToolLoads.push((async function () {\n\'use strict\';\n' + body + '\n})());\n'
      : '(function () {\n\'use strict\';\n' + body + '\n})();\n');
}
// The original lazy loader fetched these data sets when their module loaded.
out += '\n/* Reference data some tools read once they are defined. */\n' +
  '(function () {\n  [\'loadAbatements\', \'loadExemptPilot\'].forEach(function (fn) {\n' +
  '    try { if (typeof window[fn] === \'function\') window.__wdHomeToolLoads.push(Promise.resolve(window[fn]())); } catch (_) {}\n  });\n' +
  '  // Resolves once reference data has settled; a failed load never blocks a section.\n' +
  '  window.NJPropertyToolsReady = Promise.all(window.__wdHomeToolLoads.map(function (p) { return Promise.resolve(p).catch(function () {}); }));\n})();\n';

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) { console.error(OUT + ' is stale. Run: node scripts/build-home-tools.mjs'); process.exit(1); }
  console.log('Property Home tools bundle is current (' + order.length + ' modules).');
} else {
  fs.writeFileSync(OUT, out);
  console.log('Wrote ' + OUT + ' (' + order.length + ' modules, ' + Math.round(out.length / 1024) + ' KB).');
}
