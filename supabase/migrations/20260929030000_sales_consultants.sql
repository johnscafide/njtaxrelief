-- Sales consultants: a commission-only seller with her own scoped desk.
--
-- What this adds
--   * account_role 'sales_consultant' on profiles. Same idea as developer but
--     without developer tools: Pro+ access comes from a manual entitlement row
--     (source 'sales-consultant'), never from the developer bypass.
--   * watchdog_sales_consultants: one row per consultant with a share code and
--     a commission plan (rates, holds, attribution window) stored as JSON.
--   * watchdog_sales_attributions: which referred account belongs to which
--     consultant, claimed from a share link (?sc=CODE) after sign-in or
--     assigned by the owner for an offline sale. One attribution per account.
--   * watchdog_sales_commissions: the ledger. Rows are created by triggers from
--     the existing billing records (lifetime purchases and paid invoices), held
--     for a refund window, then paid or voided by the owner. Nothing here moves
--     money; the owner pays outside Stripe and records the payout reference.
--   * watchdog_sales_prospects: the consultant's own pipeline (people she is
--     working, entered by her). Consultant-owned rows; owner can read.
--
-- Access
--   Consultant: read her consultant row, her attributions, her commissions;
--   full control of her prospects. Owner (developer or admin): read everything,
--   provision or end a consultant, assign an attribution, mark commissions paid
--   or void. All writes to consultants, attributions and commissions go through
--   security definer functions or triggers; RLS blocks direct writes.

