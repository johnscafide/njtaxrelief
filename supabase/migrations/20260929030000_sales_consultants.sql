-- ---------------------------------------------------------------------------
-- The desk: one read for a consultant (herself) or the owner (any consultant)
-- ---------------------------------------------------------------------------
create or replace function public.get_sales_desk(p_consultant uuid default null)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
stable
as $$
declare
  v_uid uuid := auth.uid();
  v_target uuid := coalesce(p_consultant, auth.uid());
  v_owner boolean := public.is_watchdog_owner();
  v_consultant jsonb;
  v_totals jsonb;
  v_accounts jsonb;
  v_commissions jsonb;
  v_prospects jsonb;
begin
  if v_uid is null then raise exception 'Sign in required.'; end if;
  if v_target <> v_uid and not v_owner then raise exception 'Owner access required.'; end if;
  if v_target = v_uid and not v_owner and not exists (select 1 from public.watchdog_sales_consultants c where c.consultant_user_id = v_uid) then
    raise exception 'This account is not a sales consultant.';
  end if;

  select to_jsonb(c) into v_consultant from public.watchdog_sales_consultants c where c.consultant_user_id = v_target;
  if v_consultant is null then return jsonb_build_object('consultant', null, 'is_owner', v_owner); end if;

  select jsonb_build_object(
    'attributed', (select count(*) from public.watchdog_sales_attributions a where a.consultant_user_id = v_target),
    'active_plans', (select count(*) from public.watchdog_sales_attributions a join public.account_entitlements e on e.user_id = a.referred_user_id
                      where a.consultant_user_id = v_target and (e.subscription_status in ('active', 'trialing', 'past_due') or e.billing_interval = 'lifetime')),
    'lifetime_sales', (select count(*) from public.watchdog_sales_commissions m where m.consultant_user_id = v_target and m.kind = 'lifetime' and m.status <> 'void'),
    'pending_cents', (select coalesce(sum(m.commission_cents), 0) from public.watchdog_sales_commissions m where m.consultant_user_id = v_target and m.status = 'pending' and m.hold_until > now()),
    'eligible_cents', (select coalesce(sum(m.commission_cents), 0) from public.watchdog_sales_commissions m where m.consultant_user_id = v_target and (m.status = 'eligible' or (m.status = 'pending' and m.hold_until <= now()))),
    'paid_cents', (select coalesce(sum(m.commission_cents), 0) from public.watchdog_sales_commissions m where m.consultant_user_id = v_target and m.status = 'paid'),
    'clawback_cents', (select coalesce(sum(m.commission_cents), 0) from public.watchdog_sales_commissions m where m.consultant_user_id = v_target and m.status = 'clawback')
  ) into v_totals;

  select coalesce(jsonb_agg(jsonb_build_object(
      'referred_user_id', a.referred_user_id,
      'email', u.email,
      'name', coalesce(nullif(p.display_name, ''), nullif(p.full_name, ''), ''),
      'attributed_at', a.attributed_at,
      'expires_at', a.expires_at,
      'source', a.source,
      'plan_tier', coalesce(e.billing_tier, e.plan_tier, 'standard'),
      'subscription_status', coalesce(e.subscription_status, 'none'),
      'billing_interval', e.billing_interval,
      'commission_cents', (select coalesce(sum(m.commission_cents), 0) from public.watchdog_sales_commissions m where m.referred_user_id = a.referred_user_id and m.status <> 'void')
    ) order by a.attributed_at desc), '[]'::jsonb) into v_accounts
  from public.watchdog_sales_attributions a
  join auth.users u on u.id = a.referred_user_id
  left join public.profiles p on p.id = a.referred_user_id
  left join public.account_entitlements e on e.user_id = a.referred_user_id
  where a.consultant_user_id = v_target;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id', m.id, 'kind', m.kind, 'tier', m.tier, 'gross_cents', m.gross_cents, 'rate_bps', m.rate_bps,
      'commission_cents', m.commission_cents,
      'status', case when m.status = 'pending' and m.hold_until <= now() then 'eligible' else m.status end,
      'hold_until', m.hold_until, 'paid_at', m.paid_at, 'payout_ref', m.payout_ref, 'void_reason', m.void_reason,
      'created_at', m.created_at, 'email', u.email
    ) order by m.created_at desc), '[]'::jsonb) into v_commissions
  from public.watchdog_sales_commissions m
  left join auth.users u on u.id = m.referred_user_id
  where m.consultant_user_id = v_target;

  select coalesce(jsonb_agg(to_jsonb(s) order by s.updated_at desc), '[]'::jsonb) into v_prospects
  from public.watchdog_sales_prospects s where s.consultant_user_id = v_target;

  return jsonb_build_object('consultant', v_consultant, 'is_owner', v_owner, 'totals', v_totals, 'accounts', v_accounts, 'commissions', v_commissions, 'prospects', v_prospects);
end;
$$;
revoke all on function public.get_sales_desk(uuid) from public, anon;
grant execute on function public.get_sales_desk(uuid) to authenticated;

