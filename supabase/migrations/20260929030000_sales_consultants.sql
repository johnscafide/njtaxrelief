-- Accrue a lifetime commission for a paid Founding Lifetime purchase.
create or replace function public.watchdog_sales_accrue_lifetime(p_session_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_purchase public.billing_lifetime_purchases%rowtype;
  v_attr public.watchdog_sales_attributions%rowtype;
  v_plan jsonb;
  v_bps integer;
  v_hold integer;
  v_has_prior boolean;
begin
  select * into v_purchase from public.billing_lifetime_purchases where checkout_session_id = p_session_id;
  if not found or v_purchase.status <> 'paid' then return; end if;
  select a.* into v_attr from public.watchdog_sales_attributions a where a.referred_user_id = v_purchase.user_id;
  if not found then return; end if;
  select exists(select 1 from public.watchdog_sales_commissions where referred_user_id = v_purchase.user_id and status <> 'void') into v_has_prior;
  if not v_has_prior and (v_purchase.purchased_at < v_attr.attributed_at or v_purchase.purchased_at > v_attr.expires_at) then return; end if;
  select c.commission_plan into v_plan from public.watchdog_sales_consultants c where c.consultant_user_id = v_attr.consultant_user_id and c.status <> 'ended';
  if v_plan is null then return; end if;
  v_bps := public.watchdog_sales_plan_int(v_plan, 'lifetime_bps', 2000);
  v_hold := public.watchdog_sales_plan_int(v_plan, 'lifetime_hold_days', 30);
  insert into public.watchdog_sales_commissions
    (consultant_user_id, referred_user_id, attribution_id, kind, tier, gross_cents, rate_bps, commission_cents, currency, hold_until, source_ref)
  values
    (v_attr.consultant_user_id, v_purchase.user_id, v_attr.id, 'lifetime', v_purchase.tier, v_purchase.amount_cents, v_bps,
     (v_purchase.amount_cents * v_bps) / 10000, coalesce(v_purchase.currency, 'usd'),
     v_purchase.purchased_at + make_interval(days => v_hold), 'lifetime:' || v_purchase.checkout_session_id)
  on conflict (source_ref) do nothing;
end;
$$;
revoke all on function public.watchdog_sales_accrue_lifetime(text) from public, anon, authenticated;

-- Accrue a subscription commission from a recorded paid invoice.
create or replace function public.watchdog_sales_accrue_invoice(p_audit_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.access_audit_log%rowtype;
  v_attr public.watchdog_sales_attributions%rowtype;
  v_ent record;
  v_plan jsonb;
  v_prior integer;
  v_has_prior boolean;
  v_kind text;
  v_bps integer;
  v_hold integer;
  v_paid integer;
  v_gross integer;
  v_invoice text;
begin
  select * into v_row from public.access_audit_log where id = p_audit_id;
  if not found or v_row.event_type <> 'billing.invoice_paid' or v_row.user_id is null then return; end if;
  v_invoice := nullif(v_row.metadata->>'invoice_id', '');
  if v_invoice is null then return; end if;
  select a.* into v_attr from public.watchdog_sales_attributions a where a.referred_user_id = v_row.user_id;
  if not found then return; end if;
  select count(*) into v_prior from public.watchdog_sales_commissions
    where referred_user_id = v_row.user_id and kind in ('yearly_first', 'monthly', 'renewal') and status <> 'void';
  v_has_prior := v_prior > 0;
  if not v_has_prior and (v_row.created_at < v_attr.attributed_at or v_row.created_at > v_attr.expires_at) then return; end if;
  select e.billing_tier, e.billing_interval into v_ent from public.account_entitlements e where e.user_id = v_row.user_id;
  if v_ent.billing_tier is null or v_ent.billing_interval not in ('monthly', 'yearly') then return; end if;
  select c.commission_plan into v_plan from public.watchdog_sales_consultants c where c.consultant_user_id = v_attr.consultant_user_id and c.status <> 'ended';
  if v_plan is null then return; end if;

  v_paid := coalesce(nullif(v_row.metadata->>'amount_paid', '')::integer, 0);
  -- Commission base is the catalog price, capped by what was actually paid,
  -- so sales tax collected on top of the plan never inflates the base.
  v_gross := least(v_paid, public.watchdog_sales_catalog_cents(v_ent.billing_tier, v_ent.billing_interval));
  if v_gross <= 0 then return; end if;

  if v_ent.billing_interval = 'yearly' then
    if v_prior = 0 then
      v_kind := 'yearly_first'; v_bps := public.watchdog_sales_plan_int(v_plan, 'yearly_first_bps', 2000); v_hold := public.watchdog_sales_plan_int(v_plan, 'yearly_hold_days', 60);
    else
      v_kind := 'renewal'; v_bps := public.watchdog_sales_plan_int(v_plan, 'renewal_bps', 1000); v_hold := public.watchdog_sales_plan_int(v_plan, 'renewal_hold_days', 30);
    end if;
  else
    if v_prior < public.watchdog_sales_plan_int(v_plan, 'monthly_months', 12) then
      v_kind := 'monthly'; v_bps := public.watchdog_sales_plan_int(v_plan, 'monthly_bps', 2000); v_hold := public.watchdog_sales_plan_int(v_plan, 'monthly_hold_days', 14);
    else
      v_kind := 'renewal'; v_bps := public.watchdog_sales_plan_int(v_plan, 'renewal_bps', 1000); v_hold := public.watchdog_sales_plan_int(v_plan, 'renewal_hold_days', 30);
    end if;
  end if;

  insert into public.watchdog_sales_commissions
    (consultant_user_id, referred_user_id, attribution_id, kind, tier, gross_cents, rate_bps, commission_cents, hold_until, source_ref)
  values
    (v_attr.consultant_user_id, v_row.user_id, v_attr.id, v_kind, v_ent.billing_tier, v_gross, v_bps, (v_gross * v_bps) / 10000,
     v_row.created_at + make_interval(days => v_hold), 'invoice:' || v_invoice)
  on conflict (source_ref) do nothing;
end;
$$;
revoke all on function public.watchdog_sales_accrue_invoice(bigint) from public, anon, authenticated;

-- Refunds: anything still held is voided; anything already paid is flagged for
-- clawback so the owner can net it against the next payout.
create or replace function public.watchdog_sales_void_for_user(p_user uuid, p_reason text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.watchdog_sales_commissions
    set status = case when status = 'paid' then 'clawback' else 'void' end,
        void_reason = p_reason, updated_at = now()
  where referred_user_id = p_user
    and status in ('pending', 'eligible', 'paid')
    and created_at >= now() - interval '120 days';
$$;
revoke all on function public.watchdog_sales_void_for_user(uuid, text) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Triggers on existing billing records
-- ---------------------------------------------------------------------------
create or replace function public.watchdog_sales_lifetime_trigger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' and new.status = 'paid' then
    perform public.watchdog_sales_accrue_lifetime(new.checkout_session_id);
  elsif tg_op = 'UPDATE' and new.status in ('refunded', 'partially_refunded') and coalesce(old.status, '') = 'paid' then
    update public.watchdog_sales_commissions
      set status = case when status = 'paid' then 'clawback' else 'void' end,
          void_reason = 'lifetime purchase ' || new.status, updated_at = now()
    where source_ref = 'lifetime:' || new.checkout_session_id and status in ('pending', 'eligible', 'paid');
  end if;
  return new;
end;
$$;
drop trigger if exists watchdog_sales_lifetime_accrual on public.billing_lifetime_purchases;
create trigger watchdog_sales_lifetime_accrual
  after insert or update of status on public.billing_lifetime_purchases
  for each row execute function public.watchdog_sales_lifetime_trigger();

create or replace function public.watchdog_sales_audit_trigger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.event_type = 'billing.invoice_paid' then
    perform public.watchdog_sales_accrue_invoice(new.id);
  elsif new.event_type = 'billing.subscription_refund_observed' and new.user_id is not null then
    perform public.watchdog_sales_void_for_user(new.user_id, 'subscription refund observed');
  end if;
  return new;
end;
$$;
drop trigger if exists watchdog_sales_audit_accrual on public.access_audit_log;
create trigger watchdog_sales_audit_accrual
  after insert on public.access_audit_log
  for each row
  when (new.event_type in ('billing.invoice_paid', 'billing.subscription_refund_observed'))
  execute function public.watchdog_sales_audit_trigger();

-- ---------------------------------------------------------------------------
-- Consultant-facing: claim an attribution from a share link
-- ---------------------------------------------------------------------------
create or replace function public.claim_my_sales_attribution(p_code text, p_landing_path text default null)
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_code text := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
  v_created timestamptz;
  v_consultant public.watchdog_sales_consultants%rowtype;
  v_days integer;
  v_inserted integer;
begin
  if v_uid is null then return false; end if;
  if v_code !~ '^SC[A-Z0-9]{6,12}$' then return false; end if;
  select created_at into v_created from auth.users where id = v_uid;
  if v_created is null or v_created < now() - interval '30 days' then return false; end if;
  select * into v_consultant from public.watchdog_sales_consultants where consultant_code = v_code and status = 'active';
  if not found or v_consultant.consultant_user_id = v_uid then return false; end if;
  v_days := public.watchdog_sales_plan_int(v_consultant.commission_plan, 'attribution_days', 180);
  insert into public.watchdog_sales_attributions(referred_user_id, consultant_user_id, consultant_code, source, expires_at, landing_path)
  values (v_uid, v_consultant.consultant_user_id, v_code, 'link', now() + make_interval(days => v_days), left(coalesce(p_landing_path, ''), 240))
  on conflict (referred_user_id) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted > 0 then
    perform public.watchdog_sales_audit(v_uid, 'sales.attribution_claimed', 'sales_attribution', v_code, jsonb_build_object('consultant_user_id', v_consultant.consultant_user_id, 'source', 'link'));
  end if;
  return v_inserted > 0;
end;
$$;
revoke all on function public.claim_my_sales_attribution(text, text) from public, anon;
grant execute on function public.claim_my_sales_attribution(text, text) to authenticated;

-- ---------------------------------------------------------------------------
-- Owner-facing: provision, end, assign, mark, list
-- ---------------------------------------------------------------------------
create or replace function public.provision_sales_consultant(p_email text, p_display_name text, p_code text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_owner uuid := auth.uid();
  v_user uuid;
  v_role text;
  v_code text := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
  v_ent record;
  v_row public.watchdog_sales_consultants%rowtype;
begin
  if not public.is_watchdog_owner() then raise exception 'Owner access required.'; end if;
  if coalesce(trim(p_display_name), '') = '' then raise exception 'A display name is required.'; end if;
  select id into v_user from auth.users where lower(email) = lower(trim(coalesce(p_email, ''))) limit 1;
  if v_user is null then raise exception 'No Watchdog account uses that email. Ask her to create a free account first, then provision.'; end if;
  if v_user = v_owner then raise exception 'You cannot provision your own account as a consultant.'; end if;
  select account_role into v_role from public.profiles where id = v_user;
  if v_role in ('developer', 'admin') then raise exception 'That account is an owner account; it cannot be a consultant.'; end if;
  select provider, subscription_status, provider_subscription_id into v_ent from public.account_entitlements where user_id = v_user;
  if v_ent.provider = 'stripe' and v_ent.provider_subscription_id is not null and v_ent.subscription_status in ('active', 'trialing', 'past_due', 'paused') then
    raise exception 'That account has a live Stripe subscription. End it before granting consultant access.';
  end if;

  if v_code = '' then
    loop
      v_code := 'SC' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
      exit when not exists (select 1 from public.watchdog_sales_consultants where consultant_code = v_code);
    end loop;
  end if;
  if v_code !~ '^SC[A-Z0-9]{6,12}$' then raise exception 'Codes look like SC followed by 6 to 12 letters or digits.'; end if;

  insert into public.watchdog_sales_consultants(consultant_user_id, consultant_code, display_name, status, started_at, ended_at, created_by)
  values (v_user, v_code, trim(p_display_name), 'active', now(), null, v_owner)
  on conflict (consultant_user_id) do update
    set display_name = excluded.display_name, status = 'active', ended_at = null, updated_at = now(),
        consultant_code = case when public.watchdog_sales_consultants.status = 'ended' then excluded.consultant_code else public.watchdog_sales_consultants.consultant_code end;

  update public.profiles set account_role = 'sales_consultant' where id = v_user and account_role = 'user';

  insert into public.account_entitlements(user_id, plan_tier, subscription_status, provider, source, billing_tier, billing_interval, property_capacity, updated_at)
  values (v_user, 'pro_plus', 'active', 'manual', 'sales-consultant', 'pro_plus', null, 2500, now())
  on conflict (user_id) do update
    set plan_tier = 'pro_plus', subscription_status = 'active', provider = 'manual', source = 'sales-consultant',
        billing_tier = 'pro_plus', billing_interval = null, property_capacity = 2500,
        provider_customer_id = null, provider_subscription_id = null, updated_at = now();

  perform public.watchdog_sales_audit(v_user, 'sales.consultant_provisioned', 'sales_consultant', v_code, jsonb_build_object('by', v_owner, 'display_name', trim(p_display_name)));
  select * into v_row from public.watchdog_sales_consultants where consultant_user_id = v_user;
  return to_jsonb(v_row);
end;
$$;
