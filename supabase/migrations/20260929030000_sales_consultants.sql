-- Offline sale: the owner attaches an account to a consultant by email. Any
-- lifetime purchase or paid invoice from the last 45 days is accrued right away.
create or replace function public.assign_sales_attribution(p_email text, p_code text, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user uuid;
  v_code text := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
  v_consultant public.watchdog_sales_consultants%rowtype;
  v_days integer;
  v_inserted integer;
  r record;
begin
  if not public.is_watchdog_owner() then raise exception 'Owner access required.'; end if;
  select id into v_user from auth.users where lower(email) = lower(trim(coalesce(p_email, ''))) limit 1;
  if v_user is null then raise exception 'No Watchdog account uses that email.'; end if;
  select * into v_consultant from public.watchdog_sales_consultants where consultant_code = v_code;
  if not found then raise exception 'Unknown consultant code.'; end if;
  if v_consultant.consultant_user_id = v_user then raise exception 'A consultant cannot be attributed to herself.'; end if;
  v_days := public.watchdog_sales_plan_int(v_consultant.commission_plan, 'attribution_days', 180);
  insert into public.watchdog_sales_attributions(referred_user_id, consultant_user_id, consultant_code, source, attributed_at, expires_at, assigned_by, note)
  values (v_user, v_consultant.consultant_user_id, v_code, 'manual', now() - interval '45 days', now() + make_interval(days => v_days), auth.uid(), left(coalesce(p_note, ''), 500))
  on conflict (referred_user_id) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    return jsonb_build_object('assigned', false, 'reason', 'That account already has an attribution.');
  end if;
  perform public.watchdog_sales_audit(v_user, 'sales.attribution_assigned', 'sales_attribution', v_code, jsonb_build_object('by', auth.uid(), 'note', left(coalesce(p_note, ''), 500)));
  for r in select checkout_session_id from public.billing_lifetime_purchases where user_id = v_user and status = 'paid' and purchased_at >= now() - interval '45 days' loop
    perform public.watchdog_sales_accrue_lifetime(r.checkout_session_id);
  end loop;
  for r in select id from public.access_audit_log where user_id = v_user and event_type = 'billing.invoice_paid' and created_at >= now() - interval '45 days' order by created_at loop
    perform public.watchdog_sales_accrue_invoice(r.id);
  end loop;
  return jsonb_build_object('assigned', true, 'consultant_user_id', v_consultant.consultant_user_id);
end;
$$;
revoke all on function public.assign_sales_attribution(text, text, text) from public, anon;
grant execute on function public.assign_sales_attribution(text, text, text) to authenticated;

create or replace function public.mark_sales_commission(p_id bigint, p_status text, p_ref text default null, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.watchdog_sales_commissions%rowtype;
begin
  if not public.is_watchdog_owner() then raise exception 'Owner access required.'; end if;
  if p_status not in ('paid', 'void') then raise exception 'Status must be paid or void.'; end if;
  select * into v_row from public.watchdog_sales_commissions where id = p_id for update;
  if not found then raise exception 'Commission not found.'; end if;
  if p_status = 'paid' then
    if v_row.status not in ('pending', 'eligible') then raise exception 'Only a pending or eligible commission can be marked paid.'; end if;
    update public.watchdog_sales_commissions
      set status = 'paid', paid_at = now(), payout_ref = left(coalesce(p_ref, ''), 120), note = coalesce(left(p_note, 500), note), updated_at = now()
    where id = p_id;
  else
    if v_row.status = 'paid' then raise exception 'A paid commission cannot be voided; it becomes a clawback only through a refund.'; end if;
    update public.watchdog_sales_commissions
      set status = 'void', void_reason = left(coalesce(p_note, 'voided by owner'), 500), updated_at = now()
    where id = p_id;
  end if;
  perform public.watchdog_sales_audit(v_row.consultant_user_id, 'sales.commission_' || p_status, 'sales_commission', p_id::text, jsonb_build_object('by', auth.uid(), 'ref', p_ref, 'note', p_note, 'commission_cents', v_row.commission_cents));
  select * into v_row from public.watchdog_sales_commissions where id = p_id;
  return to_jsonb(v_row);
end;
$$;
revoke all on function public.mark_sales_commission(bigint, text, text, text) from public, anon;
grant execute on function public.mark_sales_commission(bigint, text, text, text) to authenticated;

