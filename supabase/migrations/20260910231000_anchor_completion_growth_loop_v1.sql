create or replace function public.watchdog_award_points_internal(
  p_user_id uuid,
  p_action_key text,
  p_points integer,
  p_event_key text,
  p_source_type text default 'system',
  p_source_id text default null
) returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if p_user_id is null or p_points < 1 or p_points > 1000 then return false; end if;
  insert into public.watchdog_points_ledger(user_id, action_key, points, event_key, source_type, source_id)
  values (p_user_id, p_action_key, p_points, left(p_event_key,220), left(coalesce(nullif(p_source_type,''),'system'),64), left(p_source_id,160))
  on conflict (event_key) do nothing;
  return found;
end;
$$;
revoke all on function public.watchdog_award_points_internal(uuid,text,integer,text,text,text) from public, anon, authenticated;
grant execute on function public.watchdog_award_points_internal(uuid,text,integer,text,text,text) to service_role;

