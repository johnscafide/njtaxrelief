create or replace function public.record_my_anchor_completion_feedback(
  p_application_id uuid,
  p_source_category text,
  p_source_detail text default null,
  p_marketing_opt_in boolean default false
) returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_uid uuid := auth.uid(); v_permission text; v_points jsonb;
begin
  if v_uid is null then raise exception 'authentication_required'; end if;
  if p_source_category not in ('google_search','facebook','threads','instagram','tiktok','friend_family','real_estate_professional','njpropertytaxrelief','email_newsletter','other') then
    raise exception 'invalid_source_category';
  end if;
  if p_source_category='other' and length(trim(coalesce(p_source_detail,''))) < 2 then
    raise exception 'source_detail_required';
  end if;
  if not exists(select 1 from public.anchor_applications where id=p_application_id and user_id=v_uid and status='generated') then
    raise exception 'generated_application_required';
  end if;

  insert into public.anchor_completion_feedback(application_id,user_id,source_category,source_detail,marketing_opt_in_requested)
  values(p_application_id,v_uid,p_source_category,nullif(trim(left(coalesce(p_source_detail,''),240)),''),coalesce(p_marketing_opt_in,false))
  on conflict(application_id,user_id) do update set
    source_category=excluded.source_category,
    source_detail=excluded.source_detail,
    marketing_opt_in_requested=excluded.marketing_opt_in_requested,
    updated_at=now();

  if coalesce(p_marketing_opt_in,false) then
    update public.watchdog_user_lifecycle
      set contact_permission='marketing_opt_in', updated_at=now()
      where user_id=v_uid
        and contact_permission='transactional_only'
        and unsubscribed_at is null
        and suppressed_at is null;
  end if;

  perform public.record_my_anchor_funnel_event(p_application_id,'completion_feedback_saved');
  select contact_permission into v_permission from public.watchdog_user_lifecycle where user_id=v_uid;
  select public.get_my_watchdog_points() into v_points;
  return jsonb_build_object('ok',true,'contact_permission',coalesce(v_permission,'transactional_only'),'points',v_points);
end;
$$;
revoke all on function public.record_my_anchor_completion_feedback(uuid,text,text,boolean) from public, anon;
grant execute on function public.record_my_anchor_completion_feedback(uuid,text,text,boolean) to authenticated;

create or replace function public.watchdog_referral_attribution_trigger() returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_inviter uuid; v_inserted integer;
begin
  if lower(coalesce(new.first_touch_utm_source,'')) <> 'watchdog_referral'
     or lower(coalesce(new.first_touch_utm_medium,'')) <> 'member'
     or coalesce(new.first_touch_utm_campaign,'') = '' then
    return new;
  end if;
  select user_id into v_inviter from public.watchdog_referral_codes where referral_code=upper(new.first_touch_utm_campaign) limit 1;
  if v_inviter is null or v_inviter=new.user_id then return new; end if;
  insert into public.watchdog_referral_conversions(inviter_user_id,referred_user_id,referral_code)
  values(v_inviter,new.user_id,upper(new.first_touch_utm_campaign))
  on conflict(referred_user_id) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted > 0 then
    perform public.watchdog_award_points_internal(v_inviter,'verified_referral',5,'verified_referral:'||new.user_id::text,'referral',new.user_id::text);
  end if;
  return new;
end;
$$;

