create or replace function public.award_watchdog_search_point(p_user_id uuid) returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_count integer; v_key text;
begin
  if p_user_id is null or not exists(select 1 from auth.users where id=p_user_id) then return false; end if;
  select count(*) into v_count from public.watchdog_points_ledger
   where user_id=p_user_id and action_key='property_search' and occurred_at >= date_trunc('day',now());
  if v_count >= 5 then return false; end if;
  v_key := 'property_search:'||p_user_id::text||':'||to_char(now(),'YYYYMMDD')||':'||replace(gen_random_uuid()::text,'-','');
  return public.watchdog_award_points_internal(p_user_id,'property_search',1,v_key,'product_analytics',null);
end;
$$;
revoke all on function public.award_watchdog_search_point(uuid) from public, anon, authenticated;
grant execute on function public.award_watchdog_search_point(uuid) to service_role;

create or replace function public.get_my_watchdog_points() returns jsonb
language sql
stable
security definer
set search_path = public, auth
as $$
  with p as (
    select coalesce(sum(points),0)::integer as balance, count(*)::integer as awards
    from public.watchdog_points_ledger where user_id=(select auth.uid())
  )
  select jsonb_build_object(
    'balance',balance,
    'awards',awards,
    'level',case when balance >= 150 then 'Guardian' when balance >= 75 then 'Advocate' when balance >= 25 then 'Watcher' else 'Scout' end,
    'next_level_at',case when balance >= 150 then null when balance >= 75 then 150 when balance >= 25 then 75 else 25 end
  ) from p;
$$;
revoke all on function public.get_my_watchdog_points() from public, anon;
grant execute on function public.get_my_watchdog_points() to authenticated;

create or replace function public.get_or_create_my_watchdog_referral_code() returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_uid uuid := auth.uid(); v_code text; v_try integer := 0;
begin
  if v_uid is null then raise exception 'authentication_required'; end if;
  select referral_code into v_code from public.watchdog_referral_codes where user_id=v_uid;
  if v_code is not null then return v_code; end if;
  loop
    v_try := v_try + 1;
    v_code := upper(substr(replace(gen_random_uuid()::text,'-',''),1,12));
    begin
      insert into public.watchdog_referral_codes(user_id,referral_code) values(v_uid,v_code);
      return v_code;
    exception when unique_violation then
      select referral_code into v_code from public.watchdog_referral_codes where user_id=v_uid;
      if v_code is not null then return v_code; end if;
      if v_try >= 5 then raise; end if;
    end;
  end loop;
end;
$$;
revoke all on function public.get_or_create_my_watchdog_referral_code() from public, anon;
grant execute on function public.get_or_create_my_watchdog_referral_code() to authenticated;

create or replace function public.record_my_anchor_funnel_event(
  p_application_id uuid,
  p_event_name text
) returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_uid uuid := auth.uid(); v_key text;
begin
  if v_uid is null then return false; end if;
  if p_event_name not in (
    'application_started','progress_quarter','progress_half','progress_three_quarters','review_reached',
    'pdf_generated','pdf_saved_to_vault','download_clicked','print_clicked','application_reopened',
    'watchdog_cta_clicked','completion_feedback_saved','referral_share_opened'
  ) then return false; end if;
  if not exists(select 1 from public.anchor_applications where id=p_application_id and user_id=v_uid) then return false; end if;
  v_key := v_uid::text||':'||p_application_id::text||':'||p_event_name;
  insert into public.anchor_funnel_events(application_id,user_id,event_name,event_key)
  values(p_application_id,v_uid,p_event_name,v_key)
  on conflict(event_key) do nothing;
  return found;
end;
$$;
revoke all on function public.record_my_anchor_funnel_event(uuid,text) from public, anon;
