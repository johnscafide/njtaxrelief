-- NJW-322: privacy-safe ANCHOR completion growth loop, referrals and Watchdog points.
-- Never store application answers, SSNs, income, disability status, PDF contents, or vault keys here.

create table if not exists public.anchor_completion_feedback (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_category text not null check (source_category in (
    'google_search','facebook','threads','instagram','tiktok','friend_family',
    'real_estate_professional','njpropertytaxrelief','email_newsletter','other'
  )),
  source_detail text check (source_detail is null or length(source_detail) <= 240),
  marketing_opt_in_requested boolean not null default false,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (application_id, user_id),
  constraint anchor_completion_feedback_application_owner_fk
    foreign key (application_id, user_id)
    references public.anchor_applications(id, user_id)
    on delete cascade
);

comment on table public.anchor_completion_feedback is
  'Post-completion, non-sensitive ANCHOR acquisition feedback. Kept outside the encrypted application payload.';

create table if not exists public.anchor_funnel_events (
  id bigint generated by default as identity primary key,
  application_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_name text not null check (event_name in (
    'application_started','progress_quarter','progress_half','progress_three_quarters',
    'review_reached','pdf_generated','pdf_saved_to_vault','download_clicked','print_clicked',
    'application_reopened','watchdog_cta_clicked','completion_feedback_saved','referral_share_opened'
  )),
  event_key text not null unique check (length(event_key) between 20 and 220),
  occurred_at timestamptz not null default now(),
  constraint anchor_funnel_events_application_owner_fk
    foreign key (application_id, user_id)
    references public.anchor_applications(id, user_id)
    on delete cascade
);

comment on table public.anchor_funnel_events is
  'Coarse, privacy-safe ANCHOR funnel events. Route/form type and answer-derived attributes are intentionally excluded.';

create table if not exists public.watchdog_points_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action_key text not null check (action_key ~ '^[a-z0-9_]{2,64}$'),
  points integer not null check (points between 1 and 1000),
  event_key text not null unique check (length(event_key) between 8 and 220),
  source_type text not null default 'system' check (source_type ~ '^[a-z0-9_]{2,64}$'),
  source_id text check (source_id is null or length(source_id) <= 160),
  occurred_at timestamptz not null default now()
);

comment on table public.watchdog_points_ledger is
  'Server-authoritative, append-only Watchdog engagement points. Clients cannot mint or edit awards.';

create table if not exists public.watchdog_referral_codes (
  user_id uuid primary key references auth.users(id) on delete cascade,
  referral_code text not null unique check (referral_code ~ '^[A-Z0-9]{10,16}$'),
  created_at timestamptz not null default now()
);

create table if not exists public.watchdog_referral_conversions (
  id bigint generated by default as identity primary key,
  inviter_user_id uuid not null references auth.users(id) on delete cascade,
  referred_user_id uuid not null unique references auth.users(id) on delete cascade,
  referral_code text not null references public.watchdog_referral_codes(referral_code) on delete cascade,
  verified_at timestamptz not null default now(),
  check (inviter_user_id <> referred_user_id)
);

