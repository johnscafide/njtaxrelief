import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const js=read('property/js/marketing-studio-guided-build.js');
const css=read('property/css/marketing-studio-guided-build.css');
const pages=['design','customize','recipients','review'];
const html=Object.fromEntries(pages.map(p=>[p,read(`property/marketing-studio/${p}/index.html`)]));
new vm.Script(js,{filename:'marketing-studio-guided-build.js'});
assert.match(js,/const PAGES=\['design','customize','recipients','review'\]/);
assert.match(js,/marketing_creative_studio_bootstrap/);
assert.match(js,/marketing_studio_bootstrap/);
assert.match(js,/creativeReady:saved&&!dirty/);
assert.match(js,/PAGE==='customize'&&!f\.creativeReady/);
assert.match(js,/Save changes before continuing/);
assert.match(js,/PAGE==='recipients'&&!f\.recipientsReady/);
assert.match(js,/Validate recipients before review/);
assert.match(js,/PAGE==='review'/);
assert.match(js,/Use protected launch controls below/);
assert.match(js,/setStepDone\(a,f\.creativeReady\)/);
assert.match(js,/setStepDone\(a,f\.recipientsReady\)/);
assert.match(js,/setStepDone\(a,f\.quote&&f\.paid\)/);
assert.match(js,/Only authoritative valid recipients count toward the final mailing quantity/);
assert.match(js,/This guide never sends mail, captures payment, approves a production proof or changes audience membership/);
assert.match(js,/The guided flow will not silently create or change a creative/);
assert.doesNotMatch(js,/\.functions\.invoke|\bfetch\s*\(/i);
assert.doesNotMatch(js,/marketing_save_creative|marketing_approve_creative|marketing_prepare_direct_mail_recipients|marketing_studio_quote|marketing_create_checkout|marketing_approve_direct_mail_launch|marketing_set_automation_state|marketing_launch|submit_order|purchase_postage|payment_intent/i);
assert.match(js,/const save=\$\('#msc-save,\[data-pv-save\]'\)/);
const programmaticClicks=js.match(/\.click\(\)/g)||[];
assert.equal(programmaticClicks.length,1,'guided layer may programmatically click only the existing Save Creative control');
assert.match(js,/if\(save\)\{save\.click\(\);scheduleRefresh/);
assert.doesNotMatch(js,/\$\('#msc-(?:quote|fund|launch|launch-approve)'\)\.click\(/i);
for(const [page,source] of Object.entries(html)){
  assert.match(source,/marketing-studio-guided-build\.css/,`${page} must load guided build CSS`);
  assert.match(source,/marketing-studio-guided-build\.js/,`${page} must load guided build JS`);
  assert.match(source,new RegExp(`data-ms-wizard="${page}"`),`${page} wizard marker must remain intact`);
}
assert.match(css,/\.mgb-guide/);
assert.match(css,/\.mgb-gates/);
assert.match(css,/@media\(max-width:620px\)/);
assert.match(css,/\.mw-next\.mgb-nav-locked/);
console.log('Marketing guided build contract: PASS');