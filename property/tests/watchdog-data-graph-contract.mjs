import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const graphPath='property/js/dashboard/home/watchdog-data-graph.js';
const cssPath='property/css/home/watchdog-data-graph.css';
const loaderPath='property/js/dashboard/home/home-menu-sync.js';
const semanticPath='property/js/watchdog-semantic-context.js';
const semanticFunctionPath='supabase/functions/intelligence-semantic-context/index.ts';

for (const p of [graphPath,cssPath,loaderPath,semanticPath,semanticFunctionPath]) assert.equal(fs.existsSync(p),true,`${p} must exist`);
const graph=fs.readFileSync(graphPath,'utf8');
const css=fs.readFileSync(cssPath,'utf8');
const loader=fs.readFileSync(loaderPath,'utf8');
const semantic=fs.readFileSync(semanticPath,'utf8');
const semanticFunction=fs.readFileSync(semanticFunctionPath,'utf8');
new vm.Script(graph,{filename:graphPath});
new vm.Script(semantic,{filename:semanticPath});

assert.match(loader,/watchdog-data-graph\.js/,'Property Home must load the Data Graph runtime');
assert.ok(loader.indexOf('/property/js/watchdog-semantic-context.js')<loader.indexOf('/property/js/dashboard/home/watchdog-data-graph.js'),'Semantic Context must load before the Data Graph');
assert.match(graph,/WatchdogSemanticContext\.get/,'Data Graph must resolve governed Semantic Context rather than inventing counts');
for(const pack of ['identity','assessment_tax','sale_market','appeal_uniformity','permits_closing','environment_risk','municipal_pressure']) assert.match(graph,new RegExp(`'${pack}'`),`Data Graph must request governed semantic pack ${pack}`);
assert.match(graph,/state==='available'/,'Only available markers may be counted as resolved property evidence');
assert.match(graph,/truth_class/,'Graph must preserve truth-class distinctions');
assert.match(graph,/source_fact/,'Graph must distinguish source facts');
assert.match(graph,/source_reference/,'Graph must distinguish source references');
assert.match(graph,/derived_signal/,'Graph must distinguish derived signals');
assert.match(graph,/source_id\|\|m\.provider_kind/,'Graph must retain provider/source lineage');
assert.match(graph,/intelligence_findings/,'Graph may surface persisted Intelligence lineage');
assert.match(graph,/intelligence_runs/,'Graph must connect findings to model/version runs');
assert.match(graph,/recommended_actions/,'Action counts must come from persisted finding actions');
assert.match(graph,/registry_total_markers/,'Registry universe must remain distinct from property-level availability');
assert.match(graph,/selected_marker_count/,'Property-view selection count must be explicit');
assert.match(graph,/available_count/,'Actual available-marker count must be explicit');
assert.match(graph,/Registry size is not represented as property-level evidence/,'Registry breadth must never be represented as property evidence');
assert.match(graph,/does not mean Watchdog has only/,'UI must explicitly prevent registry/property-evidence count confusion');
assert.match(graph,/planned, missing or unentitled marker as available data/,'UI must not imply missing or unentitled markers are available');
assert.match(graph,/placeholder counts/,'Failure state must refuse fabricated placeholder counts');
assert.match(graph,/preserved conflicts/,'Graph must expose preserved source conflicts');
assert.match(graph,/authority policy/,'Graph must expose authority-policy lineage');
assert.match(graph,/semantic contract/,'Graph must expose semantic contract lineage');
assert.match(graph,/new IntersectionObserver/,'The broad semantic graph request must lazy-load near the viewport');
assert.match(graph,/analyst\.insertAdjacentElement\('afterend',host\)/,'Data Graph must stay directly after Watchdog Analyst Intel in the Property Home story');
assert.match(css,/#wd-property-data-graph\{grid-column:1\/-1!important/,'Graph must own full Property Home content width');
assert.match(css,/wdg-details\[hidden\]/,'Graph details disclosure must support an accessible hidden state');
assert.match(graph,/aria-expanded/,'Graph details disclosure must expose expansion state');
assert.match(semanticFunction,/https:\/\/watchdogindex\.com/,'Semantic Context must allow the current Watchdog production origin');
assert.match(semanticFunction,/https:\/\/www\.watchdogindex\.com/,'Semantic Context must allow the www Watchdog production origin');
assert.match(semanticFunction,/http:\/\/127\.0\.0\.1:4173/,'Semantic Context must allow the isolated hosted-acceptance origin');
assert.match(semanticFunction,/REGISTRY_URL="https:\/\/watchdogindex\.com\/property\/data\/marker-registry\.json"/,'Semantic Context must load the marker registry from the current Watchdog domain');
for(const [path,content] of [[graphPath,graph],[cssPath,css],[loaderPath,loader],[semanticPath,semantic]]) assert.equal(/\?v=/.test(content),false,`${path} must not introduce version query strings`);

console.log('Watchdog Data Graph lineage, truthful counting, production-origin, lazy-load, placement and asset contract passed');
